import 'app_settings.dart';

/// Text in the app languages; Urdu and English fall back to Arabic.
class SText {
  final String ar;
  final String? ur;
  final String? en;
  const SText(this.ar, {this.ur, this.en});

  String get v {
    switch (AppSettings.instance.language) {
      case 'ur':
        return ur ?? ar;
      case 'en':
        return en ?? ar;
      default:
        return ar;
    }
  }
}

/// One day's reading: a run of verses, with a name when the story has parts.
class StoryPart {
  final int surah;
  final int from;
  final int to;
  final SText? name;
  const StoryPart(this.surah, this.from, this.to, [this.name]);
  int get count => to - from + 1;
}

enum StoryGroup { prophets, nations, people }

/// «قصص قرآنية»: a story told in the Qur'an. The verses and the Sa'di tafsir
/// come from the bundled mushaf; only the summary and lessons are written here.
class QuranStory {
  final String id;
  final StoryGroup group;
  final SText name;
  final List<StoryPart> parts;
  final (int, int) keyVerse; // (surah, ayah) quoted on the Today card
  final SText summary;
  final List<SText> lessons;
  const QuranStory({
    required this.id,
    required this.group,
    required this.name,
    required this.parts,
    required this.keyVerse,
    required this.summary,
    required this.lessons,
  });

  bool get hasParts => parts.length > 1;
  int get verseCount => parts.fold(0, (n, p) => n + p.count);
}

/// A story part as one daily reading («كهف:0»).
class StoryUnit {
  final QuranStory story;
  final int index;
  const StoryUnit(this.story, this.index);
  StoryPart get part => story.parts[index];
  String get key => '${story.id}:$index';
  bool get isLast => index == story.parts.length - 1;
}

/// Every reading in daily order: the stories in list order, parts in order.
final List<StoryUnit> storyUnits = [
  for (final s in quranStories)
    for (var i = 0; i < s.parts.length; i++) StoryUnit(s, i),
];

StoryUnit? storyUnitByKey(String key) {
  for (final u in storyUnits) {
    if (u.key == key) return u;
  }
  return null;
}

